def question(unit, section, typ, prompt, target, correct, wrong, explanation, **extra):
    opts = [correct] + wrong
    assert len(opts) == 4 and len(set(opts)) == 4
    rng.shuffle(opts)
    return dict(id=f'u{unit}-{section}-{len(current)+1:02}', type=typ, prompt=prompt,
                target=target, options=opts, answer=opts.index(correct), explanation=explanation, **extra)

def add_vocab(n):
    global current
    current = []
    words = [line.split('|') for line in vocab[n].splitlines()]
    # 10 câu đọc, 8 câu chữ Hán, 10 điền từ, 6 đồng nghĩa, 6 cách dùng.
    for i, (kanji, reading, meaning) in enumerate(words[:10]):
        wrong = [w[1] for w in rng.sample([w for w in words if w[1] != reading], 3)]
        current.append(question(n,'vocabulary','reading','Chọn cách đọc đúng của từ được đánh dấu.',kanji,reading,wrong,f'{kanji} đọc là {reading}, nghĩa là {meaning}.'))
    for kanji, reading, meaning in words[10:18]:
        wrong = [w[0] for w in rng.sample([w for w in words if w[0] != kanji], 3)]
        current.append(question(n,'vocabulary','kanji','Chọn chữ Hán đúng cho từ sau.',reading,kanji,wrong,f'{reading} viết là {kanji}, nghĩa là {meaning}.'))
    for sentence, ans, wrong, exp in contexts[n]:
        current.append(question(n,'vocabulary','context','Chọn từ phù hợp để điền vào （　）.',sentence,ans,wrong,exp))
    for word, ans, wrong, exp in synonyms[n]:
        current.append(question(n,'vocabulary','synonym','Chọn cách diễn đạt gần nghĩa nhất.',word,ans,wrong,exp))
    for word, ans, wrong, exp in usage[n]:
        current.append(question(n,'vocabulary','usage','Chọn câu sử dụng từ đúng nhất.',word,ans,wrong,exp))
    assert len(current)==40
    return current

