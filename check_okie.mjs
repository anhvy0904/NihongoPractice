import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('dist/app.js','utf8').split("document.addEventListener('change'")[0];
const bank=JSON.parse(fs.readFileSync('dist/questions.json','utf8'));
const element={innerHTML:'',outerHTML:'',disabled:true,focus(){}};
const ctx=vm.createContext({document:{querySelector:()=>element,querySelectorAll:()=>[]},window:{scrollTo(){}},console});
vm.runInContext(source,ctx);
ctx.data=bank;
vm.runInContext('bank=data',ctx);
for(const [unit,section] of [...bank.units.flatMap(u=>[[u.id,'vocabulary'],[u.id,'grammar']]),['common','vocabulary']]){
 ctx.unit=unit;ctx.section=section;
 vm.runInContext('start(unit,section);checkAnswer()',ctx);
 assert.equal(vm.runInContext('session.index',ctx),0,'Blank Okie must not advance');
 vm.runInContext('updateAnswer(session.questions[0].answer);checkAnswer()',ctx);
 assert.equal(vm.runInContext('session.index',ctx),1);
 assert.equal(vm.runInContext('session.graded.filter(Boolean).length',ctx),1);
 assert.equal(vm.runInContext('session.lastFeedback.correct',ctx),true);
 vm.runInContext('checkAnswer()',ctx);
 assert.equal(vm.runInContext('session.index',ctx),1,'Repeated click must not skip blank next question');
 vm.runInContext('session.index=0;updateAnswer((session.questions[0].answer+1)%4);checkAnswer()',ctx);
 assert.equal(vm.runInContext('session.answers[0]===session.questions[0].answer',ctx),true,'Confirmed answer must stay locked');
 assert.match(vm.runInContext('questionCard()',ctx),/disabled/);
 vm.runInContext('session.index=1;updateAnswer((session.questions[1].answer+1)%4);checkAnswer()',ctx);
 assert.equal(vm.runInContext('session.lastFeedback.correct',ctx),false);
 assert.match(vm.runInContext('feedbackPanel()',ctx),/Chưa đúng/);
 vm.runInContext('while(!session.submitted){updateAnswer(session.questions[session.index].answer);checkAnswer()}',ctx);
 assert.equal(vm.runInContext('session.answers.filter((a,i)=>a===session.questions[i].answer).length',ctx),39);
 assert.match(element.innerHTML,/39<span>/);
 vm.runInContext('start(unit,section);session.index=39;updateAnswer(session.questions[39].answer);checkAnswer()',ctx);
 assert.equal(vm.runInContext('session.index',ctx),0,'Last question must wrap to unchecked questions');
 vm.runInContext('updateAnswer(session.questions[0].answer);submit()',ctx);
 assert.equal(vm.runInContext('session.answers[0]',ctx),null,'Unconfirmed answer must not count');
}
console.log('Passed: 9 sections, blank/double clicks, correct/wrong feedback, locked answers, wrapping, automatic final score and early submission.');
