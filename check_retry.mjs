import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('dist/app.js','utf8').split("document.addEventListener('change'")[0];
const bank=JSON.parse(fs.readFileSync('dist/questions.json','utf8'));
const element={innerHTML:'',outerHTML:'',disabled:true,focus(){}};
const ctx=vm.createContext({document:{querySelector:()=>element,querySelectorAll:()=>[]},window:{scrollTo(){}},console});
vm.runInContext(source,ctx);ctx.data=bank;vm.runInContext('bank=data',ctx);
const run=s=>vm.runInContext(s,ctx);
for(const [unit,section] of [...bank.units.flatMap(u=>[[u.id,'vocabulary'],[u.id,'grammar']]),['common','vocabulary']]){
 ctx.unit=unit;ctx.section=section;run('start(unit,section);checkAnswer()');
 assert.equal(run('session.index'),0,'Blank next must not advance');
 assert.match(run('questionCard()'),/>Câu tiếp<\/button>/);
 run('updateAnswer(session.questions[0].answer);checkAnswer();checkAnswer()');
 assert.equal(run('session.index'),1,'Double click cannot skip next blank question');
 run('session.index=0;updateAnswer((session.questions[0].answer+1)%4);checkAnswer()');
 assert.equal(run('session.answers[0]===session.questions[0].answer'),true,'Confirmed answer stays locked');
 run('session.index=1;updateAnswer(session.questions[1].answer);requestSubmit()');
 assert.equal(run('session.submitted'),false,'Cannot finish before all questions are submitted');
 run('while(session.retryRound===0){const q=session.questions[session.index];updateAnswer([1,39].includes(q.originalIndex)?(q.answer+1)%4:q.answer);checkAnswer()}');
 assert.equal(run('session.submitted'),false);
 assert.equal(run('session.firstScore'),38);
 assert.deepEqual(Array.from(run('session.questions.map(q=>q.originalIndex)')),[1,39]);
 assert.equal(run('session.retryRound'),1);
 run('updateAnswer(session.questions[0].answer);checkAnswer();updateAnswer((session.questions[1].answer+1)%4);checkAnswer()');
 assert.equal(run('session.retryRound'),2,'Still wrong gets another required round');
 assert.equal(run('session.questions.length'),1);
 assert.equal(run('session.questions[0].originalIndex'),39);
 run('updateAnswer(session.questions[0].answer);checkAnswer()');
 assert.equal(run('session.submitted'),true);
 assert.equal(run('session.questions.length'),40,'Final review restores all original questions');
 assert.equal(run('session.answers.filter((a,i)=>a===session.questions[i].answer).length'),40);
 assert.equal(run('session.firstScore'),38,'Original score remains accurate');
 assert.match(element.innerHTML,/38 \/ 40 câu đúng ở lượt đầu/);
 run('start(unit,section);while(!session.submitted){updateAnswer(session.questions[session.index].answer);checkAnswer()}');
 assert.equal(run('session.retryRound'),0,'Perfect first pass skips retries');
 assert.equal(run('session.firstScore'),40);
}
console.log('Passed all 9 sections: next submits, no blank/double skips, locked answers, required complete first pass, wrong-only repeated rounds, first score preservation, full final review, perfect score.');
