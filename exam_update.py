def revise_bank(bank):
    rng = random.Random(9101112)
    def make(n, section, typ, target, correct, distractors, exp, sentence=None, **extra):
        opts = [correct] + distractors
        assert len(opts)==len(set(opts))==4, (n, target, opts)
        rng.shuffle(opts)
        return dict(type=typ,prompt=INSTRUCTIONS[typ],target=target,options=opts,
                    answer=opts.index(correct),explanation=exp,**({'sentence':sentence} if sentence else {}),**extra)
    for u in bank['units']:
        n=u['id']; v=[]
        for typ, table in [('reading',READING),('kanji',KANJI)]:
            for line in table[n].splitlines():
                target,sentence,correct,wrong,exp=line.split('|')
                v.append(make(n,'vocabulary',typ,target,correct,wrong.split(','),exp,sentence=sentence))
        for line in CONTEXT[n].splitlines():
            target,correct,wrong,exp=line.split('|')
            v.append(make(n,'vocabulary','context',target,correct,wrong.split(','),exp))
        for line in SYNONYM[n].splitlines():
            target,sentence,correct,wrong,exp=line.split('|')
            v.append(make(n,'vocabulary','synonym',target,correct,wrong.split(','),exp,sentence=sentence))
        for line in USAGE[n].splitlines():
            target,correct,wrong,exp=line.split('|')
            v.append(make(n,'vocabulary','usage',target,correct,wrong.split('^'),exp))
        assert len(v)==40
        # Câu mẫu đứng đầu từng dạng; 28 câu còn lại được soạn cùng từ và ngữ cảnh.
        u['vocabulary']=v
        for index in (0,1,10,11,18,19,20,21,28,29,34,35):
            v[index]['suppliedSample']=True
        fills=[]
        for line in SAMPLE_FILL[n].splitlines():
            target,correct,wrong,pattern,exp=line.split('|')
            fills.append(make(n,'grammar','fill',target,correct,wrong.split(','),exp,pattern=pattern,suppliedSample=True))
        existing=[q for q in u['grammar'] if q['type']=='fill']
        seen={q['target'] for q in fills}
        fills.extend(q for q in existing if q['target'] not in seen)
        fills=fills[:30]
        ordered=[]
        for prefix,fragments,suffix,pattern,exp in SAMPLE_ORDER[n]:
            ordered.append(make(n,'grammar','order',prefix+'＿＿　＿＿　★　＿＿'+suffix,
                                fragments[2],[fragments[0],fragments[1],fragments[3]],exp,
                                pattern=pattern,orderedFragments=fragments,fullSentence=prefix+''.join(fragments)+suffix,suppliedSample=True))
        # Thêm câu mới; không giữ câu có cùng các mảnh của câu mẫu.
        keys={tuple(q['orderedFragments']) for q in ordered}
        ordered.extend(q for q in u['grammar'] if q['type']=='order' and tuple(q['orderedFragments']) not in keys)
        u['grammar']=fills+ordered[:10]
        assert len(u['grammar'])==40
        for section in ('vocabulary','grammar'):
            for i,q in enumerate(u[section],1):
                q['id']=f'u{n}-{section}-{i:02d}'
                q['prompt']=INSTRUCTIONS[q['type']]
                q['group']={'reading':1,'kanji':2,'context':3,'synonym':4,'usage':5,'fill':1,'order':2}[q['type']]
        u['title']={9:'Xử lý dữ liệu & kiểm thử',10:'Tiến độ & cải thiện',11:'Vận hành & phối hợp',12:'Triển khai & thành quả'}[n]
        u['patterns']=list(dict.fromkeys(q['pattern'] for q in u['grammar']))
    bank['schemaVersion']=2
    bank['sources']={
      'grammar':'Đề mẫu Unit 9–12 người dùng gửi và bốn PDF 文型リスト.',
      'formats':'Đề ミニテスト①（漢字・語彙） và ミニテスト②（文法） người dùng cung cấp trực tiếp.',
      'vocabularyNote':'Từ vựng phân theo đúng bốn đề mẫu Unit 9–12 do người dùng gửi. Mỗi phần có câu mẫu và câu bổ sung cùng từ/chủ đề.',
      'editingNote':'Một số lựa chọn trùng hoặc có nhiều cách hiểu đã được chỉnh để mỗi câu có một đáp án rõ ràng. Không áp dụng giới hạn 10 phút của đề mẫu ngắn cho bài luyện 40 câu.'
    }
    return bank
